import { DocumentItemKind, InvoiceKind } from '@prisma/client';
import { calculateTotals, CalcItem } from './calculations';

// Everything the pre-issue check needs; plain data so the rules can be unit-tested.
export interface InvoiceCheckInput {
  issuer: {
    name?: string | null;
    street?: string | null;
    zipCode?: string | null;
    city?: string | null;
    taxId?: string | null;
    vatId?: string | null;
  };
  recipient: { name?: string | null; street?: string | null; zipCode?: string | null; city?: string | null };
  details: {
    serviceDateFrom?: Date | null;
    serviceDateTo?: Date | null;
    paymentTermDays?: number | null;
    reverseCharge: boolean;
    recipientVatId?: string | null;
    kind?: InvoiceKind;
    retentionPercent?: number | null;
    retentionDueDate?: Date | null;
  };
  items: (CalcItem & { name: string })[];
}

const blank = (value: string | null | undefined) => !value || value.trim() === '';

// Checks the mandatory details of an invoice (§ 14 Abs. 4 UStG and the reverse-charge rules of § 13b)
// before it may be issued. Returns human-readable problems in German; empty = ready to issue.
// Number, date and tax breakdown are generated by the system and therefore not checked here.
export function validateInvoice(input: InvoiceCheckInput): string[] {
  const problems: string[] = [];
  const { issuer, recipient, details, items } = input;

  if ([issuer.name, issuer.street, issuer.zipCode, issuer.city].some(blank)) {
    problems.push('Firmenprofil: Name und vollständige Anschrift des Unternehmens fehlen.');
  }
  if (blank(issuer.taxId) && blank(issuer.vatId)) {
    problems.push('Firmenprofil: Steuernummer oder USt-IdNr. fehlt.');
  }
  if ([recipient.name, recipient.street, recipient.zipCode, recipient.city].some(blank)) {
    problems.push('Empfänger: Name und vollständige Anschrift fehlen (beim Kontakt ergänzen).');
  }

  if (!details.serviceDateFrom) {
    problems.push('Leistungsdatum bzw. Leistungszeitraum fehlt.');
  } else if (details.serviceDateTo && details.serviceDateTo < details.serviceDateFrom) {
    problems.push('Leistungszeitraum: Das Ende liegt vor dem Beginn.');
  }
  if (details.paymentTermDays === null || details.paymentTermDays === undefined || details.paymentTermDays < 0) {
    problems.push('Zahlungsziel fehlt.');
  }

  const positions = items.filter((item) => item.kind === DocumentItemKind.POSITION);
  if (positions.every((item) => item.isOptional)) {
    problems.push('Die Rechnung enthält keine Positionen.');
  }
  if (positions.some((item) => item.isOptional)) {
    problems.push('Optionalpositionen sind auf einer Rechnung nicht zulässig: bitte entfernen oder als normale Position übernehmen.');
  }
  if (items.some((item) => blank(item.name))) {
    problems.push('Mindestens eine Zeile hat keine Bezeichnung.');
  }
  if (positions.some((item) => !item.isOptional)) {
    const net = calculateTotals(items).net;
    if (details.kind === InvoiceKind.FINAL) {
      // A final invoice may end at 0 € (everything paid in advance) but never below.
      if (net.lt(0)) {
        problems.push('Die abgezogenen Abschlagszahlungen übersteigen den Rechnungswert (ggf. Gutschrift nötig).');
      }
    } else if (net.lte(0)) {
      problems.push('Die Rechnungssumme muss größer als 0 € sein.');
    }
  }

  if (details.retentionPercent && details.retentionPercent > 0 && !details.retentionDueDate) {
    problems.push('Sicherheitseinbehalt: Bitte angeben, wann der Einbehalt fällig wird (Ende der Gewährleistung).');
  }

  if (details.reverseCharge) {
    if (blank(issuer.vatId)) {
      problems.push('§ 13b: Die USt-IdNr. des Unternehmens muss im Firmenprofil hinterlegt sein.');
    }
    if (blank(details.recipientVatId)) {
      problems.push('§ 13b: Die USt-IdNr. des Empfängers fehlt (beim Kontakt ergänzen).');
    }
    if (positions.some((item) => !item.isOptional && Number(item.vatRate) !== 0)) {
      problems.push('§ 13b: Alle Positionen müssen den Steuersatz 0 % haben (die Steuer schuldet der Empfänger).');
    }
  }
  return problems;
}
